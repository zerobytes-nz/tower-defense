// Generates ASSETS.md from assets.manifest.json.
// Usage: npm run assets:docs          (write)
//        npm run assets:docs -- --check  (CI: fail if ASSETS.md is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadManifest } from './lib/assets.mjs';

const m = loadManifest();
const out = path.join(ROOT, 'ASSETS.md');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lic = `public/${m.roots.licensed}`, cc = `public/${m.roots.cc0}`, ph = `public/${m.roots.placeholder}`;

const groups = new Map();
for (const a of m.assets) {
  const g = a.key.split('.')[0];
  if (!groups.has(g)) groups.set(g, []);
  groups.get(g).push(a);
}
const TITLES = { bg: 'Maps', map: 'Map pieces', tower: 'Towers', unit: 'Tower crews', shot: 'Shots', fx: 'Effects', enemy: 'Enemies', ui: 'HUD / UI' };
const kit = m.sources['craftpix-td-kit'];

let md = `<!-- GENERATED by scripts/assets-docs.mjs from assets.manifest.json. Do not edit by hand: run \`npm run assets:docs\`. -->
# Art assets

Tower Defense is open source, but its art comes from a pack that may **not** be redistributed:

**[${kit.name}](${kit.url})** (CraftPix.net; [licence](${kit.licenceUrl})).
The downloaded folder is called \`craftpix-net-519305-tower-defense-2d-game-kit\` (13 sub-packs: monsters, bosses, towers, effects, GUI, tilesets).

Two more CraftPix packs (same licence) give the units: the three hero knights from
**[${m.sources['craftpix-knights'].name}](${m.sources['craftpix-knights'].url})**, and the barracks soldiers and militia from
**[${m.sources['craftpix-tactical'].name}](${m.sources['craftpix-tactical'].url})** (unzip it; only
\`2d-fantasy-people-warrior-character-sprites/\` is used). Import them with
\`npm run assets:import-packs -- --knights "<folder with PNG/silver_knight/>" --tactical "<folder with 2d-fantasy-people-warrior-character-sprites/>"\`.

So the repo holds two kinds of art:

| Folder | In git? | What goes there |
|---|---|---|
| \`${lic}/\` | ❌ **gitignored** | Sheets packed from **your** copy of the kit, by \`npm run assets:import\`. |
| \`${ph}/\` | ✅ committed | Original placeholder art (MIT), drawn by \`scripts/placeholder-art.mjs\`. Same file names, pixel sizes and frame layout as the kit sheets. |

(\`${cc}/\` is for CC0 art; none is used yet.)

For every entry in \`assets.manifest.json\`, the game loads the first of \`${lic}/<path>\`, \`${cc}/<path>\` (CC0 sources only)
and \`${ph}/<path>\` that **exists and has the exact pixel size listed below**. A fresh clone runs right away on the
placeholders. The font, [Passion One](https://fonts.google.com/specimen/Passion+One), is SIL OFL 1.1 and is committed in \`public/fonts/\`.

## Getting the real art (2 minutes)

1. **Download the kit** from [${kit.url}](${kit.url}) with your own CraftPix account, and unzip it **outside** this repo.
   Only the \`PNG/\` folders of its sub-packs are read; \`AI/\`, \`EPS/\`, \`FLA/\` and \`SCML/\` are not used.
2. **Import it:**
   \`\`\`bash
   npm run assets:import -- "/path/to/craftpix-net-519305-tower-defense-2d-game-kit"
   \`\`\`
   This only **reads** the kit. For each asset below it takes the listed kit frames (*From the kit*), samples them evenly,
   scales them (one fixed scale per character, so its animations line up), and writes the sheet into \`${lic}/\`.
   Maps are the kit's 1920×1080 backgrounds drawn at 1280×720.
3. **Check:** \`npm run assets:status\` lists every asset as ● licensed, ○ placeholder or ✖ missing, and flags wrong sizes.
4. **Run:** \`npm run dev\`. The dev server reloads when files appear.
5. **Never commit \`${lic}/\`.** \`.gitignore\` excludes it, and \`npm run check-assets\` (pre-commit hook + CI) fails if a
   licensed file is ever staged. If it fires: \`git rm --cached <file>\`.

Sheets are frames left to right, then top to bottom when the entry has \`columns\` (to stay under 4096 px for phone GPUs),
no padding. \`displayScale\` says how big a frame is drawn on the 1280×720 screen.
Art from somewhere else works too: \`npm run assets:pack -- <key> <frame files...>\` makes a sheet of the right size.

## Adding or changing an asset

Edit \`assets.manifest.json\` (key, path, size, frames, what it's for, source). If needed, add a drawer for the key in
\`scripts/placeholder-art.mjs\`. Then run \`npm run assets:placeholders && npm run assets:docs\` and commit the
manifest, the placeholder, and this file. Game code refers to assets **only by manifest key**.

## Every file to replace (${m.assets.length})
`;

for (const [g, list] of groups) {
  md += `\n### ${TITLES[g] ?? g}\n\n| Key | File (under \`${lic}/\`) | Size · frames | Used for | From the kit |\n|---|---|---|---|---|\n`;
  for (const a of list) {
    const s = m.sources[a.source];
    const size = a.type === 'audio' ? 'audio' : a.frameCount > 1
      ? `${a.width}×${a.height} · ${a.frameCount} × ${a.frameWidth}×${a.frameHeight}${a.columns ? ` (${a.columns} per row)` : ''}${a.animation?.frameRate ? ` @ ${a.animation.frameRate} fps` : ''}${a.animation?.repeat === -1 ? ', loop' : ''}`
      : `${a.width}×${a.height}${a.tile ? ' · tiles horizontally' : ''}`;
    const from = a.source === 'own' ? 'Original. Keep the placeholder.' : a.kit ? `\`${a.kit.files}\`${a.kit.crop ? ` (crop ${a.kit.crop.join(', ')})` : ''}` : `[${s.name}](${s.url})`;
    md += `| \`${a.key}\` | \`${a.path}\` | ${esc(size)} | ${esc(a.usedFor)}${a.notes ? ` ${esc(a.notes)}` : ''} | ${from} |\n`;
  }
}

md += `\n## Sources\n\n| Id | Pack | Committed? | Licence note |\n|---|---|---|---|\n`;
for (const [k, s] of Object.entries(m.sources)) {
  const where = k === 'own' ? 'yes (placeholder)' : s.cc0 ? 'yes, in \`cc0/\`' : 'no, \`licensed/\`';
  md += `| \`${k}\` | [${esc(s.name)}](${s.url}) | ${where} | ${esc(s.licence)}${s.licenceUrl ? ` [Licence](${s.licenceUrl})` : ''} |\n`;
}
md += `\nAlways read the licence on the pack's own page; the notes here are not legal advice.\n`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== md) { console.error('✖ ASSETS.md is out of date. Run: npm run assets:docs'); process.exit(1); }
  console.log('✔ ASSETS.md is up to date');
} else {
  fs.writeFileSync(out, md);
  console.log(`Wrote ASSETS.md (${m.assets.length} assets)`);
}
