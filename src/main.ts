import Phaser from 'phaser';
import { GAME_W, GAME_H, DEBUG, COLORS } from './config.ts';
import { BootScene } from './scenes/BootScene.ts';
import { MenuScene } from './scenes/MenuScene.ts';
import { GameScene } from './scenes/GameScene.ts';
import { AwiScene } from './scenes/AwiScene.ts';
import { initAudio } from './systems/audio.ts';
import './systems/install.ts'; // listen for the browser's install prompt from the very first moment

const game = new Phaser.Game({
  type: Phaser.AUTO,
  parent: 'game',
  width: GAME_W,
  height: GAME_H,
  backgroundColor: COLORS.bg,
  scale: { mode: Phaser.Scale.EXPAND, autoCenter: Phaser.Scale.CENTER_BOTH },
  render: { antialias: true, powerPreference: 'high-performance', roundPixels: false },
  fps: { target: 60, smoothStep: true },
  input: { activePointers: 2 },
  disableContextMenu: true,
  banner: false,
  audio: { noAudio: true }, // our own Web Audio synth (systems/audio.ts), not Phaser's sound manager
  dom: { createContainer: true }, // the player-code box on the Connect screen
  scene: [BootScene, MenuScene, GameScene, AwiScene],
});

initAudio();

// Offline play + "Add to Home Screen" (production builds only; sw.js is generated by vite.config.ts).
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => { navigator.serviceWorker.register('./sw.js').catch(() => { /* offline play is optional */ }); });
}

if (DEBUG) (window as unknown as { __game: Phaser.Game }).__game = game;
